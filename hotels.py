"""hotels.py - the two "tools" the AI is allowed to call: search_hotels() and book_hotel().

REAL data : hotel names, locations, star ratings (from OpenStreetMap, free, no key).
MOCK data : prices, room availability, and bookings (generated by this code / stored in SQLite).

If you later get a real booking API, only the inside of these two functions has to change.
"""
import random
import re
import string
from datetime import date, datetime

import requests

from db import get_conn

CURRENCY = "INR"
# Rough nightly price by star rating (0 = unknown stars). Change to taste.
STAR_BASE_PRICE = {0: 2500, 1: 1200, 2: 2000, 3: 3500, 4: 6500, 5: 12000}
DEMO_NOTICE = "DEMO booking - this is NOT a real reservation."
# OpenStreetMap asks every client to identify itself.
HEADERS = {"User-Agent": "TravelChatbotDemo/1.0 (learning project)"}


# ---------------------------------------------------------------- real hotels (OSM)
def _parse_stars(value):
    """OSM stores stars as text like "4" or "4S". Return an int 0-5 (0 = unknown)."""
    match = re.search(r"\d", value or "")  # find the first digit
    return min(int(match.group()), 5) if match else 0


def _fetch_from_osm(city):
    """Ask OpenStreetMap for hotels in a city. Returns a list of dicts (may be empty)."""
    # Step 1: Nominatim turns "Goa" into a bounding box (south, north, west, east).
    geo = requests.get(
        "https://nominatim.openstreetmap.org/search",
        params={"q": city, "format": "json", "limit": 1},
        headers=HEADERS,
        timeout=15,
    ).json()
    if not geo:
        return []
    south, north, west, east = map(float, geo[0]["boundingbox"])

    # Step 2: Overpass finds every named tourism=hotel inside that box.
    # "node" = a point, "way" = a building outline; "out center" gives ways a single point too.
    query = f"""[out:json][timeout:25];
    (node["tourism"="hotel"]["name"]({south},{west},{north},{east});
     way["tourism"="hotel"]["name"]({south},{west},{north},{east}););
    out center 80;"""
    data = requests.post(
        "https://overpass-api.de/api/interpreter",
        data={"data": query},
        headers=HEADERS,
        timeout=40,
    ).json()

    hotels = []
    for el in data.get("elements", []):
        tags = el.get("tags", {})
        point = el.get("center", el)  # ways have "center", nodes have lat/lon directly
        hotels.append(
            {
                "name": tags["name"],
                "stars": _parse_stars(tags.get("stars")),
                "lat": point.get("lat"),
                "lon": point.get("lon"),
                "website": tags.get("website"),
                "address": tags.get("addr:street"),
                "source": "osm",
            }
        )
    hotels.sort(key=lambda h: -h["stars"])  # rated hotels first
    return hotels[:40]


def _get_city_hotels(city):
    """Return REAL hotel rows for a city (OpenStreetMap), cached in SQLite. Never invents hotels.

    Returns (rows, problem). problem is None, "unreachable" (OSM failed) or "none_found".
    """
    key = city.strip().lower()
    with get_conn() as conn:
        # Remove invented hotels saved by older versions of this app (keep any that have bookings).
        conn.execute(
            "DELETE FROM hotels WHERE source != 'osm' AND id NOT IN (SELECT hotel_id FROM bookings)"
        )
        rows = conn.execute("SELECT * FROM hotels WHERE city = ? AND source = 'osm'", (key,)).fetchall()
        if rows:
            return rows, None

        try:
            found = _fetch_from_osm(city)
        except Exception:  # no internet, OSM busy, bad JSON... never crash the chat
            return [], "unreachable"  # not cached, so the next search tries again
        if not found:
            return [], "none_found"

        for h in found:
            conn.execute(
                "INSERT INTO hotels (city, name, stars, lat, lon, website, address, source) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (key, h["name"], h["stars"], h["lat"], h["lon"], h["website"], h["address"], "osm"),
            )
        return conn.execute("SELECT * FROM hotels WHERE city = ? AND source = 'osm'", (key,)).fetchall(), None


# ---------------------------------------------------------------- mock prices & rooms
def _nightly_price(hotel_id, stars, check_in):
    """Deterministic fake price: same hotel + same date always gives the same price."""
    rng = random.Random(f"price-{hotel_id}-{check_in}")  # seeded -> repeatable
    return int(round(STAR_BASE_PRICE[stars] * rng.uniform(0.85, 1.25) / 50) * 50)


def _rooms_left(conn, hotel_id, check_in, check_out):
    """Fake room count (0-5) minus demo bookings that overlap the requested dates."""
    rng = random.Random(f"rooms-{hotel_id}-{check_in}")
    total = rng.randint(0, 5)
    booked = conn.execute(
        "SELECT COUNT(*) FROM bookings WHERE hotel_id = ? AND check_in < ? AND check_out > ?",
        (hotel_id, check_out, check_in),
    ).fetchone()[0]
    return max(total - booked, 0)


def _validate_dates(check_in, check_out):
    """Return (nights, None) if dates are fine, or (None, error_message)."""
    try:
        d_in = date.fromisoformat(check_in)
        d_out = date.fromisoformat(check_out)
    except ValueError:
        return None, "Dates must be in YYYY-MM-DD format."
    if d_in < date.today():
        return None, "Check-in date is in the past."
    if d_out <= d_in:
        return None, "Check-out must be after check-in."
    return (d_out - d_in).days, None


# ---------------------------------------------------------------- the two AI tools
# The AI reads each function's name, type hints and docstring to know when and how to call it.
def search_hotels(city: str, check_in: str, check_out: str, guests: int = 2, max_price_per_night: int = 0) -> dict:
    """Search available hotels in a city for given dates.

    Args:
        city: City or place name, e.g. "Goa" or "Shimla".
        check_in: Check-in date as YYYY-MM-DD.
        check_out: Check-out date as YYYY-MM-DD.
        guests: Number of guests.
        max_price_per_night: Maximum price per night in INR. Use 0 for no limit.

    Returns:
        A dict with a list of available hotels (hotel_id, name, stars, price_per_night, rooms_left).
    """
    nights, error = _validate_dates(check_in, check_out)
    if error:
        return {"error": error}

    hotel_rows, problem = _get_city_hotels(city)
    if problem == "unreachable":
        return {"results": [], "message": "Could not reach the hotel data source (OpenStreetMap). Try again in a minute."}
    if problem == "none_found":
        return {"results": [], "message": f"No hotels found for '{city}'. Try a bigger nearby city or check the spelling."}

    results = []
    for h in hotel_rows:
        with get_conn() as conn:
            rooms = _rooms_left(conn, h["id"], check_in, check_out)
        if rooms == 0:
            continue  # fully booked -> don't show
        price = _nightly_price(h["id"], h["stars"], check_in)
        if max_price_per_night and price > max_price_per_night:
            continue
        results.append(
            {
                "hotel_id": h["id"],
                "name": h["name"],
                "stars": h["stars"] or "unrated",
                "price_per_night": price,
                "total_price": price * nights,
                "currency": CURRENCY,
                "rooms_left": rooms,
                "website": h["website"],
                "hotel_data_source": h["source"],  # always "osm" = real hotel
            }
        )

    results.sort(key=lambda r: r["price_per_night"])  # cheapest first
    if not results:
        return {"results": [], "message": "No hotels available for these dates/budget."}
    return {"nights": nights, "guests": guests, "results": results[:6], "note": "Prices and availability are simulated."}


def book_hotel(user_id: int, hotel_id: int, guest_name: str, check_in: str, check_out: str, guests: int = 2) -> dict:
    """Book a hotel room (demo booking). Only call after the user confirmed the hotel, dates and guest name.

    Args:
        user_id: Id of the logged-in user who owns the booking (set by the server, never by the AI).
        hotel_id: The hotel_id returned by search_hotels.
        guest_name: Full name of the guest.
        check_in: Check-in date as YYYY-MM-DD.
        check_out: Check-out date as YYYY-MM-DD.
        guests: Number of guests.

    Returns:
        A dict with the booking reference and details, or an error.
    """
    nights, error = _validate_dates(check_in, check_out)
    if error:
        return {"error": error}

    with get_conn() as conn:
        hotel = conn.execute("SELECT * FROM hotels WHERE id = ?", (hotel_id,)).fetchone()
        if not hotel:
            return {"error": f"Unknown hotel_id {hotel_id}. Search again first."}
        # Re-check availability right before booking (someone may have booked meanwhile).
        if _rooms_left(conn, hotel_id, check_in, check_out) == 0:
            return {"error": "Sorry, no rooms left for those dates."}

        total = _nightly_price(hotel_id, hotel["stars"], check_in) * nights
        ref = "DEMO-" + "".join(random.choices(string.ascii_uppercase + string.digits, k=6))
        conn.execute(
            "INSERT INTO bookings (ref, hotel_id, guest_name, check_in, check_out, guests, total_price, created_at, user_id) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (ref, hotel_id, guest_name, check_in, check_out, guests, total, datetime.now().isoformat(timespec="seconds"), user_id),
        )

    return {
        "status": "confirmed",
        "booking_ref": ref,
        "hotel": hotel["name"],
        "guest_name": guest_name,
        "check_in": check_in,
        "check_out": check_out,
        "nights": nights,
        "total_price": total,
        "currency": CURRENCY,
        "notice": DEMO_NOTICE,
    }